package com.sshborg.mosh

import com.sshborg.TestConfig
import com.sshborg.terminal.TerminalEmulator
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Test
import java.io.File

/**
 * Phase 5's gate: does our emulator draw what mosh's optimiser meant?
 *
 * This is the one remaining question that can still cost real work, and it needs an oracle rather
 * than an opinion. Under SSH the bytes reaching the emulator are the remote program's own output,
 * and a misreading is usually repaired by the next full redraw. Under mosh they are generated by
 * `Display::new_frame`, which sends only the cells that changed, positions the cursor absolutely,
 * picks `ECH` or a scroll region when they are cheaper, and — this is the part that bites —
 * **believes it already knows what our screen looks like**. A disagreement about one cell is never
 * corrected; everything after it is drawn in the wrong place.
 *
 * So the test records the host byte stream of a scripted session and replays it into our emulator,
 * writing the resulting grid out as text. `scripts/mosh-gate.sh` replays the identical bytes
 * through a second, independent emulator — a detached `tmux` pane of the same size — and diffs the
 * two renderings. Two emulators disagreeing about the same bytes is a defect in one of them; two
 * agreeing is the only evidence worth having here.
 *
 * Each checkpoint records the stream **from the beginning of the session**, not since the previous
 * checkpoint, because a mosh frame is a diff against the screen the server thinks we hold: a later
 * fragment of the stream means nothing on its own.
 *
 * The replay has one trap in it, and it is the reason the script runs `stty raw` before `cat`.
 * Mosh's bytes are generated in user space and never pass through a pty, and `mosh-client` puts
 * the real terminal in raw mode, so a bare LF means "down one row" and nothing else. Replay the
 * same bytes through a pty with the default `onlcr` and every LF silently becomes a carriage
 * return as well — the oracle would then disagree with us about every wrapped line, and the fault
 * would be the rig's.
 */
class MoshRepaintGateTest {

    private val configured = TestConfig.moshServer()
    private val outDir = TestConfig.moshGateOut()

    @Test fun `a scripted session is recorded for the oracle, and a resize reaches the pty`() {
        assumeTrue(TestConfig.NO_MOSH_SERVER, configured != null)
        assumeTrue("no -PmoshGateOut given; scripts/mosh-gate.sh sets it", outDir != null)
        val out = outDir!!
        out.listFiles()?.forEach { it.delete() }

        val session = MoshLabSession(configured!!)
        var step = 0
        try {
            session.resize(COLUMNS, ROWS)

            // A neutral prompt before anything is recorded: deterministic, and it keeps the
            // machine's user and host name out of the recording, which the oracle's files would
            // otherwise carry around.
            session.type("export TERM=xterm-256color; PS1='$ '; clear\r")
            assertTrue("the shell never settled", session.awaitQuiet())

            // A checkpoint per step, not per scenario: a full-screen editor is only interesting
            // while it is open, and after `:q!` the alternate screen has already put back what was
            // underneath it.
            for ((name, script) in SCENARIOS) {
                for ((n, keys) in script.withIndex()) {
                    session.send(keys)
                    assertTrue("$name step $n never settled", session.awaitQuiet())
                    checkpoint(session, out, ++step, "$name-$n")
                }
            }

            assertColoursArrived()

            // Programs whose screen contains a clock, a load average or a process list cannot be
            // diffed against anything. They are still worth recording: the two renderings go side
            // by side for a person to look at, which is how the parts of the gate that no
            // assertion can reach get checked at all.
            for ((name, script) in MANUAL_SCENARIOS) {
                for ((n, keys) in script.withIndex()) {
                    session.send(keys)
                    assertTrue("$name step $n never settled", session.awaitQuiet())
                    checkpoint(session, out, ++step, "manual-$name-$n")
                }
            }

            // Gate step three: the resize has to reach the far end's pty, not merely our own
            // buffer. Asking the shell what size it thinks it is, is the whole proof.
            session.resize(RESIZED_COLUMNS, RESIZED_ROWS)
            session.type("printf 'size=%sx%s\\n' \"$(tput cols)\" \"$(tput lines)\"\r")
            assertTrue(
                "the resize never reached the remote pty; the host last sent:\n" + session.outputTail(),
                session.awaitOutput("size=${RESIZED_COLUMNS}x$RESIZED_ROWS", 10_000),
            )

            assertTrue("the closing handshake went unanswered", session.shutdown(5_000))
            assertEquals("datagrams were dropped as unparseable", 0, session.protocolErrors)
            assertEquals("the server reused a fragment id for different bytes", 0, session.conflictingFragments)
        } finally {
            session.close()
        }
        println("repaint gate: $step checkpoints recorded in $out")
    }

    /** What each checkpoint's screen looked like to us, by step name, for the colour assertions. */
    private val screens = HashMap<String, TerminalEmulator>()

    /** Writes the stream so far, and what our emulator makes of it, side by side. */
    private fun checkpoint(session: MoshLabSession, out: File, step: Int, name: String) {
        val stream = session.recorded.toByteArray()
        val prefix = "%02d-%s".format(step, name)
        val emulator = replay(stream)
        screens[name] = emulator
        File(out, "$prefix.bin").writeBytes(stream)
        File(out, "$prefix.ours.txt").writeText(asText(emulator))
        File(out, "$prefix.size").writeText("$COLUMNS $ROWS\n")
    }

    /**
     * The attribute half of the gate, which no text comparison can reach: a cell in the wrong
     * colour still holds the right character. The `colour-cells` scenario painted one cell per
     * palette entry at a known row, so here the right answer is known in advance.
     */
    private fun assertColoursArrived() {
        val palette = screens["colour-cells-0"] ?: error("the 256-colour row was never recorded")
        for (i in 0 until 64) {
            val cell = palette.buffer.getCell(CELL_ROW_256, i)
            assertEquals("column $i of the 256-colour row holds the wrong character", 'X'.code, cell.code)
            assertEquals("column $i of the 256-colour row has the wrong background", i, cell.style.bg)
        }
        val rgb = screens["colour-cells-1"] ?: error("the true-colour row was never recorded")
        for (i in 0 until 64) {
            val cell = rgb.buffer.getCell(CELL_ROW_RGB, i)
            val expected = 0x1000000 or ((i * 4) shl 16) or ((255 - i * 4) shl 8) or 7
            assertEquals("column $i of the true-colour row holds the wrong character", 'Y'.code, cell.code)
            assertEquals("column $i of the true-colour row has the wrong background", expected, cell.style.bg)
        }
    }

    /**
     * Replays a recorded stream into a fresh emulator and returns the screen as text, in the shape
     * `tmux capture-pane -p` produces it: one line per row, trailing blanks gone, and no trailing
     * blank rows. A fresh emulator per checkpoint, because the stream always starts at the top.
     */
    private fun replay(stream: ByteArray): TerminalEmulator =
        TerminalEmulator(COLUMNS, ROWS).apply { process(stream, 0, stream.size) }

    private fun asText(emulator: TerminalEmulator): String {
        val rows = (0 until ROWS).map { emulator.buffer.getRowText(it) }
        return rows.dropLastWhile { it.isBlank() }.joinToString("\n", postfix = "\n")
    }

    private companion object {
        const val COLUMNS = 100
        const val ROWS = 30
        const val CELL_ROW_256 = 10
        const val CELL_ROW_RGB = 12
        const val RESIZED_COLUMNS = 120
        const val RESIZED_ROWS = 40

        const val ESC = "\u001b"

        /**
         * What to type, and what each one is for. Every scenario has to be deterministic, because
         * the oracle compares text: `htop` and anything else showing a clock or a load average
         * belongs in the manual pass, not here.
         */
        val SCENARIOS: List<Pair<String, List<ByteArray>>> = listOf(
            // Wide characters straddling the right margin, at four different offsets. This is the
            // place our CharWidth table and the server's wcwidth() have to agree, and the place
            // mosh leans on the terminal's own deferred wrap.
            "wide-margin" to typed(
                "clear; for n in 96 97 98 99; do printf 'A%.0s' \$(seq 1 \$n); printf '\\u65e5\\u672c\\u8a9e\\n'; done",
            ),
            // The 256-colour cube and a true-colour ramp: mosh re-expresses colour runs its own
            // way, and a mis-parsed SGR shows up as the wrong cell contents too.
            "colours" to typed(
                "clear; for i in \$(seq 0 231); do printf '\\033[48;5;%dm%3d' \$i \$i; done; printf '\\033[0m\\n'",
                "for i in \$(seq 0 79); do printf '\\033[48;2;%d;%d;%dm.' \$((i*3)) \$((255-i*3)) 128; done; printf '\\033[0m\\n'",
            ),
            // Partial updates in place: a scroll region, absolute positioning, and erases. These
            // are the moves mosh picks when they are cheaper than redrawing, and the ones a
            // program would rarely make by itself.
            "partial" to typed(
                "clear; for r in \$(seq 1 25); do printf '\\033[%d;1Hrow %02d %s\\n' \$r \$r \"\$(printf 'B%.0s' \$(seq 1 60))\"; done",
                "tput csr 5 15; tput cup 15 0; printf 'scrolled %d\\n' 1 2 3 4 5 6 7 8; tput csr 0 29",
                "tput cup 8 10; printf '\\033[30X'; tput cup 12 0; printf '\\033[K'; tput cup 28 0",
            ),
            // Colour, at known coordinates. The text diff against tmux cannot see an attribute:
            // a cell in the wrong colour holds the right character and the oracle shrugs. So this
            // one is painted at a fixed row with one cell per colour, and asserted directly
            // afterwards — the only part of the gate where we know the right answer in advance and
            // do not need a second emulator to tell us.
            "colour-cells" to typed(
                "clear; tput cup $CELL_ROW_256 0; for i in \$(seq 0 63); do printf '\\033[48;5;%dmX' \$i; done; printf '\\033[0m'",
                "tput cup $CELL_ROW_RGB 0; for i in \$(seq 0 63); do printf '\\033[48;2;%d;%d;%dmY' \$((i*4)) \$((255-i*4)) 7; done; printf '\\033[0m'",
            ),
            // A pager: a reverse-video status line, and a screen repainted by scrolling.
            "less" to listOf(
                bytes("clear; less -X /etc/services\r"),
                bytes(" "),      // page down
                bytes(" "),
                bytes("q"),
                bytes("\r"),
            ),
            // A full-screen editor: its own alternate-screen handling, a status line, and a
            // repaint driven by cursor movement rather than by output.
            "vim" to listOf(
                bytes("clear; vim -u NONE -c 'set nocompatible number' /etc/services\r"),
                bytes(":40\r"),                        // jump to line 40, repainting the screen
                bytes("${ESC}[B${ESC}[B${ESC}[B"),
                bytes("$ESC:q!\r"),
            ),
        )

        /**
         * Recorded, rendered both ways, and never diffed: nothing here draws the same screen
         * twice. `htop` earns its place because it is the densest partial-update program most
         * people have to hand — colour bars, a full-width header, and a process list redrawn in
         * place once a second.
         */
        val MANUAL_SCENARIOS: List<Pair<String, List<ByteArray>>> = listOf(
            "htop" to listOf(
                bytes("clear; htop -d 20\r"),
                bytes(""),          // nothing typed: just let it redraw once on its own
                bytes("q"),
            ),
        )

        /**
         * One shell command per element, each ending in a carriage return. The `\033` and
         * `\uXXXX` in the scenario text are passed through to the shell as the characters they
         * look like, for its own `printf` to interpret: that keeps one layer of escaping out of
         * the Kotlin source, and it keeps the test's *input* plain ASCII, so a wide-character
         * fault can only be about what came back.
         */
        private fun typed(vararg commands: String): List<ByteArray> =
            commands.map { bytes(it + "\r") }

        private fun bytes(s: String): ByteArray = s.toByteArray()
    }
}
